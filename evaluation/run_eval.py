"""Compare extraction methods on held-out test sets.

Test sets
  dataturks : 221 real resumes never seen in training (seeded split, see training/prepare_data.py)
  synthetic : 30 hand-written resumes with hand-written ground truth (different style / domain shift)

Methods
  heuristics  : regex + gazetteer baseline (no ML)
  base        : off-the-shelf pretrained NER (dslim/bert-base-NER) - generic PER/ORG/LOC, NO resume fine-tuning
  finetuned   : DistilBERT fine-tuned on the training split (this project)
  llm         : optional few-shot LLM (needs OPENAI_API_KEY or a local Ollama server)

Usage
  python -m evaluation.run_eval --methods heuristics,base,finetuned
"""
import argparse
import json
from pathlib import Path

from src.config import ENTITY_TYPES, FINETUNED_DIR, resolve_model_path, OFF_THE_SHELF_MAP, OFF_THE_SHELF_NER, \
    RESULTS_DIR, SPLIT_DIR, SYNTHETIC_TEST_FILE
from evaluation.metrics import evaluate, paired_bootstrap, per_doc_counts


def load_dataturks_test():
    docs = []
    for line in open(SPLIT_DIR / "test.jsonl", encoding="utf-8"):
        r = json.loads(line)
        gold = {l: [] for l in ENTITY_TYPES}
        for s, e, l in r["entities"]:
            gold[l].append(r["text"][s:e])
        docs.append((r["text"], gold))
    return docs


def load_synthetic_test():
    docs = []
    for r in json.load(open(SYNTHETIC_TEST_FILE, encoding="utf-8")):
        gold = {l: r["ground_truth"].get(l, []) for l in ENTITY_TYPES}
        docs.append((r["text"], gold))
    return docs


def build_method(name, finetuned_path):
    if name == "heuristics":
        from src.extraction import heuristics
        return heuristics.predict_strings, ENTITY_TYPES
    if name == "base":
        from src.extraction.ner import TransformerNER
        m = TransformerNER(OFF_THE_SHELF_NER, label_map=OFF_THE_SHELF_MAP)
        return m.predict_strings, list(OFF_THE_SHELF_MAP.values())   # only what it can possibly predict
    if name == "finetuned":
        from src.extraction.ner import TransformerNER
        if not Path(finetuned_path).exists() and "/" not in str(finetuned_path):
            raise FileNotFoundError(f"{finetuned_path} not found - run training/finetune.py first")
        return TransformerNER(str(finetuned_path)).predict_strings, ENTITY_TYPES
    if name == "llm":
        from src.extraction.llm import LLMExtractor
        return LLMExtractor().predict_strings, ENTITY_TYPES
    raise ValueError(name)


def fmt(v):
    return f"{100 * v:5.1f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--methods", default="heuristics,base,finetuned")
    ap.add_argument("--finetuned_path", default=resolve_model_path())
    ap.add_argument("--max_docs", type=int, default=None, help="debug: limit docs per test set")
    args = ap.parse_args()

    RESULTS_DIR.mkdir(exist_ok=True)
    test_sets = {"dataturks": load_dataturks_test(), "synthetic": load_synthetic_test()}
    if args.max_docs:
        test_sets = {k: v[:args.max_docs] for k, v in test_sets.items()}

    all_results, all_errors, all_counts = {}, {}, {}
    for m in args.methods.split(","):
        try:
            predict, covered = build_method(m, args.finetuned_path)
        except Exception as e:
            print(f"[skip] {m}: {e}")
            continue
        for ts_name, docs in test_sets.items():
            preds = [predict(t) for t, _ in docs]
            golds = [g for _, g in docs]
            for mode in ("exact", "partial"):
                table, errs = evaluate(golds, preds, ENTITY_TYPES, mode)
                all_results.setdefault(ts_name, {}).setdefault(m, {})[mode] = table
                if mode == "exact":
                    all_errors.setdefault(ts_name, {})[m] = errs
            shared = list(OFF_THE_SHELF_MAP.values())
            all_counts.setdefault(ts_name, {})[m] = {
                "all": per_doc_counts(golds, preds, ENTITY_TYPES),
                "shared": per_doc_counts(golds, preds, shared)}
            print(f"[done] {m} on {ts_name}: micro-F1(exact)={fmt(all_results[ts_name][m]['exact']['micro']['f1'])}")

    json.dump(all_results, open(RESULTS_DIR / "metrics.json", "w"), indent=1)
    write_markdown(all_results, all_errors, all_counts, test_sets)
    plot(all_results)
    print(f"\nWrote {RESULTS_DIR}/metrics.json, comparison.md, error_analysis.md, f1_by_label.png")


def write_markdown(res, errs, counts, test_sets):
    L = ["# Evaluation results (auto-generated by `evaluation/run_eval.py`)\n"]
    for ts, methods in res.items():
        L.append(f"\n## Test set: `{ts}` ({len(test_sets[ts])} resumes)\n")
        for mode in ("exact", "partial"):
            L.append(f"\n**{mode.title()} match** - F1 (%) per entity type\n")
            labels = ENTITY_TYPES + ["micro", "macro"]
            L.append("| Method | " + " | ".join(labels) + " |")
            L.append("|---|" + "---|" * len(labels))
            for m, t in methods.items():
                row = [fmt(t[mode][l]["f1"]) if t[mode][l]["support"] and (t[mode][l]["tp"] + t[mode][l]["fp"] > 0 or l in ("macro",))
                       else "n/a" if t[mode][l]["tp"] + t[mode][l]["fp"] == 0 else "0.0" for l in labels]
                L.append(f"| {m} | " + " | ".join(row) + " |")
            L.append("")
            L.append("| Method | micro-P | micro-R | micro-F1 |")
            L.append("|---|---|---|---|")
            for m, t in methods.items():
                mi = t[mode]["micro"]
                L.append(f"| {m} | {fmt(mi['precision'])} | {fmt(mi['recall'])} | {fmt(mi['f1'])} |")
        # significance: base vs finetuned
        if "base" in counts.get(ts, {}) and "finetuned" in counts[ts]:
            L.append(f"\n### Does fine-tuning help? (paired bootstrap over documents, exact match, micro-F1)\n")
            for scope, desc in (("shared", "Name+Company+Location (labels the base model can predict)"),
                                ("all", "all 6 entity types")):
                a, b, d, lo, hi, p = paired_bootstrap(counts[ts]["base"][scope], counts[ts]["finetuned"][scope])
                L.append(f"- {desc}: base {fmt(a)} -> fine-tuned {fmt(b)} | diff {100*d:+.1f} pts, "
                         f"95% CI [{100*lo:+.1f}, {100*hi:+.1f}], P(no improvement) = {p:.3f}")
    open(RESULTS_DIR / "comparison.md", "w").write("\n".join(L) + "\n")

    E = ["# Error analysis (exact match; up to 8 examples per type)\n"]
    for ts, methods in errs.items():
        for m, per_label in methods.items():
            E.append(f"\n## {m} on `{ts}`\n")
            for l, d in per_label.items():
                if not d["fp"] and not d["fn"]:
                    continue
                E.append(f"**{l}** - {len(d['fp'])} false positives, {len(d['fn'])} false negatives")
                E.append("- FP (predicted, not in gold): " + "; ".join(f"`{x}`" for _, x in d["fp"][:8]))
                E.append("- FN (in gold, missed):       " + "; ".join(f"`{x}`" for _, x in d["fn"][:8]) + "\n")
    open(RESULTS_DIR / "error_analysis.md", "w").write("\n".join(E) + "\n")


def plot(res):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
    fig, axes = plt.subplots(1, len(res), figsize=(7 * len(res), 4), squeeze=False)
    for ax, (ts, methods) in zip(axes[0], res.items()):
        labels = ENTITY_TYPES
        w = 0.8 / max(len(methods), 1)
        for i, (m, t) in enumerate(methods.items()):
            ax.bar(np.arange(len(labels)) + i * w, [100 * t["exact"][l]["f1"] for l in labels], w, label=m)
        ax.set_xticks(np.arange(len(labels)) + w * (len(methods) - 1) / 2)
        ax.set_xticklabels(labels, rotation=20)
        ax.set_ylabel("F1 (%) - exact match")
        ax.set_title(f"Test set: {ts}")
        ax.legend()
    plt.tight_layout()
    plt.savefig(RESULTS_DIR / "f1_by_label.png", dpi=150)


if __name__ == "__main__":
    main()
